#!/usr/bin/env python3
"""Generate plugins/hornero-emoji/EmojiData.qml from Unicode's emoji-test.txt.

usage: gen_emoji_data.py <emoji-test.txt> [output.qml]

Data source: https://unicode.org/Public/emoji/16.0/emoji-test.txt
(Unicode 16.0, (c) Unicode, Inc., Unicode License v3,
https://www.unicode.org/license.txt). Only fully-qualified emoji are kept.
Entries that differ only by a skin tone modifier collapse into one base entry
that carries its five tone variants, so the picker can apply the person's
tone setting without shipping five rows per emoji.
Line format: emoji|name|group|tone1,tone2,tone3,tone4,tone5 (tones optional,
light to dark). Output is deterministic.
"""
import re
import sys
from pathlib import Path

TONES = [0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF]
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E[0-9.]+\s+(.+)$")
GROUP_SHORT = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "nature",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}


def parse(path: Path):
    group = ""
    entries = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        if raw.startswith("# group:"):
            group = raw.split(":", 1)[1].strip()
            continue
        if group == "Component" or raw.startswith("#") or not raw.strip():
            continue
        match = LINE.match(raw)
        if not match:
            continue
        codepoints = [int(cp, 16) for cp in match.group(1).split()]
        entries.append((codepoints, match.group(2).strip(), GROUP_SHORT[group]))
    return entries


def collapse(entries):
    base = {}
    order = []
    toned = {}
    for codepoints, name, group in entries:
        used = [cp for cp in codepoints if cp in TONES]
        if not used:
            key = tuple(codepoints)
            base[key] = (name, group)
            order.append(key)
            toned.setdefault(key, {})
            continue
        if len(set(used)) != 1 or len(used) != 1:
            continue  # two-person sequences with mixed tones are not offered
        tone = TONES.index(used[0])
        stripped = tuple(cp for cp in codepoints if cp not in TONES)
        toned.setdefault(stripped, {})[tone] = "".join(chr(cp) for cp in codepoints)
    return base, order, toned


def main(argv):
    if not 1 <= len(argv) <= 2:
        print(__doc__, file=sys.stderr)
        return 2
    base, order, toned = collapse(parse(Path(argv[0])))
    lines = []
    for key in order:
        name, group = base[key]
        variants = toned.get(key) or toned.get(key + ()) or {}
        # Sequences such as "waving hand" store the toned form under the
        # base without the VS16 (U+FE0F); match on the stripped base too.
        if not variants:
            stripped = tuple(cp for cp in key if cp != 0xFE0F)
            variants = toned.get(stripped, {})
        tones = ",".join(variants[i] for i in range(5)) if len(variants) == 5 else ""
        lines.append("|".join(("".join(chr(cp) for cp in key), name, group, tones)))
    body = "\\n".join(lines)
    out = f'''import QtQuick

// GENERATED by scripts/gen_emoji_data.py from Unicode emoji-test.txt 16.0
// (c) 2024 Unicode, Inc. Distributed under the Unicode License v3
// (unicode.org/license, no URL scheme here on purpose). Do not edit by hand.
// Line format: emoji|name|group|five skin-tone variants (light to dark).
QtObject {{
    readonly property string unicodeVersion: "16.0"
    readonly property string raw: "{body}"
}}
'''
    target = Path(argv[1]) if len(argv) == 2 else Path(__file__).resolve().parent.parent / "plugins" / "hornero-emoji" / "EmojiData.qml"
    target.write_text(out, encoding="utf-8")
    print(f"{len(lines)} emoji, {sum(1 for l in lines if l.endswith(',') is False and l.count('|') == 3 and l.split('|')[3])} with tones -> {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
